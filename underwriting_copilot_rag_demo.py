# DEMO RUN
# ---------------------------------------------------------------------------

if __name__ == "__main__":
    print("STEP 1 — extracting text from PDFs with pdfplumber...")
    pages = extract_documents()
    print(f"  {len(pages)} pages extracted from {len(set(p['doc_name'] for p in pages))} documents\n")

    print("STEP 2 — semantic chunking...")
    chunks = semantic_chunk(pages)
    print(f"  {len(chunks)} chunks produced")
    for c in chunks[:3]:
        print(f"    [{c['chunk_id']}] {c['doc_name']} p{c['page_num']}: {c['text'][:70]}...")
    print()

    print("STEP 3 — embedding chunks...")
    embedder = Embedder([c["text"] for c in chunks])
    print(f"  embedding source: {'OpenAI text-embedding-3-small' if embedder.use_openai else 'local TF-IDF fallback (no OPENAI_API_KEY set)'}\n")
    vectors = embedder.embed([c["text"] for c in chunks])

    print("STEP 4 — building FAISS index...")
    index = build_index(vectors)
    print(f"  index has {index.ntotal} vectors, dim {index.d}\n")

    print("STEP 5 — retrieval: raw query vs expanded query")
    raw_q = "why was this flagged?"
    risk_factors = ["Sum Assured to Income Ratio 18x annual income", "No medical loading declared at age 58",
                     "Agent Persistency Rate 34% vs branch avg 72%"]

    used_text, raw_results = retrieve(raw_q, embedder, index, chunks, k=3)
    print(f"  RAW query: \"{raw_q}\"")
    for r in raw_results:
        print(f"    score {r['score']:.3f}  [{r['doc_name']} p{r['page_num']}] {r['text'][:65]}...")

    used_text, exp_results = retrieve(raw_q, embedder, index, chunks, k=3, risk_factors=risk_factors, do_expand=True)
    print(f"\n  EXPANDED query: \"{used_text[:90]}...\"")
    for r in exp_results:
        print(f"    score {r['score']:.3f}  [{r['doc_name']} p{r['page_num']}] {r['text'][:65]}...")
    print()

    print("STEP 6 — evaluating retrieval quality (precision@3 / recall@3)...")
    eval_set = [
        {"query": "what happens if the claim is within the contestability period",
         "relevant_chunk_ids": [12]},
        {"query": "when is a secondary medical review required",
         "relevant_chunk_ids": [0]},
        {"query": "how should investigators handle the sourcing agent's history",
         "relevant_chunk_ids": [4]},
    ]
    metrics = evaluate(eval_set, embedder, index, chunks, k=3)
    print(f"  {metrics}\n")

    print("STEP 7 — generating final answer for the expanded-query retrieval...")
    answer = generate_answer(raw_q, exp_results)
    print(f"  {answer}")
